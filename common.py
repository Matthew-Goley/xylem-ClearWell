def result(status="OK", reason="", warnings=None, details=None):
    """Every stage function returns one of these dicts.

    status is one of: OK, NOT RUN, FAILED.
    """
    return {"status": status, "reason": reason, "warnings": list(warnings or []),
            "details": details or {}}


def marker_path(paths, stage):
    return paths.markers / f"{stage}.done"


def write_marker(paths, stage, info):
    paths.markers.mkdir(parents=True, exist_ok=True)
    with open(marker_path(paths, stage), "w") as f:
        json.dump(info, f, indent=2, default=str)


def load_status(paths):
    status_file = paths.results / "status.json"
    if status_file.exists():
        with open(status_file) as f:
            return json.load(f)
    return {"stages": {}}


def save_status(paths, status, stage_order):
    paths.results.mkdir(parents=True, exist_ok=True)
    with open(paths.results / "status.json", "w") as f:
        json.dump(status, f, indent=2, default=str)
    write_status_md(paths, status, stage_order)


def record_stage(paths, stage, res, runtime_s, stage_order):
    """Store the outcome of one stage in results/status.json and STATUS.md."""
    status = load_status(paths)
    status["stages"][stage] = {
        "status": res["status"],
        "reason": res.get("reason", ""),
        "warnings": res.get("warnings", []),
        "runtime_s": round(float(runtime_s), 1),
        "finished_at": datetime.now().isoformat(timespec="seconds"),
        "smoke": paths.smoke,
    }
    status["environment"] = config.environment_summary()
    save_status(paths, status, stage_order)


def _status_table(status, stage_order):
    lines = ["| Stage | Status | Runtime (s) | Finished | Reason |",
             "|---|---|---|---|---|"]
    stages = status.get("stages", {})
    for name in stage_order:
        entry = stages.get(name)
        if entry is None:
            lines.append(f"| {name} | NOT RUN | | | stage has not been run yet |")
            continue
        reason = str(entry.get("reason", "")).replace("|", "/").replace("\n", " ")
        lines.append(f"| {name} | {entry['status']} | {entry.get('runtime_s', '')} | "
                     f"{entry.get('finished_at', '')} | {reason[:300]} |")
    return lines


def write_status_md(paths, status, stage_order):
    """Write results/STATUS.md from status.json. Never edit STATUS.md by hand."""
    mode = "SMOKE run (tiny test, numbers are NOT meaningful)" if paths.smoke else "FULL run"
    lines = [f"# Clearwell pipeline status: {mode}", "",
             (f"Generated by code at {datetime.now().isoformat(timespec='seconds')}. "
             "Do not edit by hand; rerun `python run_all.py --stage summary` to refresh."), ""]
    lines += _status_table(status, stage_order)
    warnings = [(n, w) for n, e in status.get("stages", {}).items() for w in e.get("warnings", [])]
    lines += ["", "## Warnings", ""]
    if warnings:
        lines += [f"- **{n}**: {w}" for n, w in warnings]
    else:
        lines.append("- none recorded")
    env = status.get("environment", {})
    lines += ["", "## Machine that produced this file", ""]
    lines += [f"- {k}: {v}" for k, v in env.items()]
    if not env.get("cuda_available", False):
        lines.append("- NOTE: no CUDA GPU on this machine, so any training here was CPU only.")

    # In the full STATUS.md, also show the latest smoke run (if one exists).
    if not paths.smoke:
        smoke_status = paths.results / "smoke" / "status.json"
        if smoke_status.exists():
            with open(smoke_status) as f:
                smoke = json.load(f)
            lines += ["", "## Latest smoke run on this machine (code check only)", "",
                      ("Smoke runs use a handful of tiles, 1 epoch and a tiny area. They show "
                      "that the code runs, not how well it works."), ""]
            lines += _status_table(smoke, stage_order)
            smoke_warn = [(n, w) for n, e in smoke.get("stages", {}).items()
                          for w in e.get("warnings", [])]
            if smoke_warn:
                lines += ["", "Smoke warnings:", ""]
                lines += [f"- **{n}**: {w}" for n, w in smoke_warn]
    notes = paths.results / "status_notes.md"
    if notes.exists() and not paths.smoke:
        lines += ["", notes.read_text(encoding="utf-8").strip()]
    (paths.results / "STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


