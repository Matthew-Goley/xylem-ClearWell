def is_permanent_error(err):
    """Errors that will not go away by retrying (blocked, not found, no access)."""
    text = str(err)
    for code in ("401", "403", "404", "Forbidden", "Not Found", "Tunnel connection failed"):
        if code in text:
            return True
    return False


def retry(func, *args, tries=None, wait_s=5, what="network call", logger=None, **kwargs):
    """Call func(*args, **kwargs), retrying with growing waits on errors."""
    tries = tries or config.NETWORK_RETRIES
    for attempt in range(1, tries + 1):
        try:
            return func(*args, **kwargs)
        except Exception as err:  # noqa: BLE001 - we really want to retry anything
            if attempt == tries or is_permanent_error(err):
                raise
            delay = wait_s * 2 ** (attempt - 1)
            if logger:
                logger.warning(f"{what} failed (attempt {attempt}/{tries}): {err}. "
                               f"Retrying in {delay} s")
            time.sleep(delay)


def http_session():
    import requests
    session = requests.Session()
    session.headers["User-Agent"] = "clearwell-student-project/1.0"
    return session


def download_file(url, dest, logger=None, timeout=60, max_bytes=None):
    """Download url to dest with resume support. Skips if dest already exists.

    The file is written to dest + '.part' first and renamed when complete, so a
    half-finished download never looks finished.
    """
    dest = Path(dest)
    if dest.exists() and dest.stat().st_size > 0:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")

    def _do():
        from tqdm import tqdm
        session = http_session()
        done = part.stat().st_size if part.exists() else 0
        headers = {"Range": f"bytes={done}-"} if done else {}
        with session.get(url, stream=True, timeout=timeout, headers=headers) as resp:
            if resp.status_code == 416:  # already complete
                return
            resp.raise_for_status()
            if done and resp.status_code != 206:  # server ignored the Range header
                done = 0
            total = int(resp.headers.get("Content-Length", 0)) + done
            if max_bytes and total > max_bytes:
                raise RuntimeError(f"{url} is {total / 1e9:.2f} GB, above the limit "
                                   f"of {max_bytes / 1e9:.2f} GB")
            mode = "ab" if done else "wb"
            with open(part, mode) as f, tqdm(total=total or None, initial=done, unit="B",
                                             unit_scale=True, desc=dest.name,
                                             disable=not sys.stdout.isatty()) as bar:
                for chunk in resp.iter_content(chunk_size=1 << 20):
                    f.write(chunk)
                    bar.update(len(chunk))

    retry(_do, what=f"download {url}", logger=logger)
    os.replace(part, dest)
    if logger:
        logger.info(f"Downloaded {url} -> {dest} ({dest.stat().st_size / 1e6:.1f} MB)")
    return dest


