def dem_on_grid(paths, aoi, logger):
    """Copernicus DEM 30 m resampled (bilinear) onto the flood-map grid.

    Tries Planetary Computer (cop-dem-glo-30) first, then the public AWS
    bucket. Returns the path of outputs/dem_on_grid.tif or None.
    """
    import rasterio
    from rasterio.warp import Resampling, reproject

    out = paths.outputs / "dem_on_grid.tif"
    if out.exists():
        return out
    crs, transform, width, height = aoi_grid(aoi)
    lon_min, lat_min, lon_max, lat_max = aoi["bbox_lonlat"]

    # 1) Planetary Computer
    try:
        import odc.stac
        from odc.geo.geobox import GeoBox
        catalog = open_planetary_computer()
        items = list(catalog.search(collections=[config.DEM_COLLECTION],
                                    bbox=aoi["bbox_lonlat"]).items())
        if not items:
            raise RuntimeError("no DEM items found")
        gbox = GeoBox((height, width), transform, crs)
        ds = odc.stac.load(items, bands=["data"], geobox=gbox, resampling="bilinear",
                           chunks={"x": 2048, "y": 2048}, dtype="float32", nodata=np.nan)
        # DEM tiles may carry different dates; merge them all into one layer.
        dem = ds["data"].max(dim="time", skipna=True).values.astype("float32")
        write_tif(out, dem, crs, transform, nodata=np.nan)
        logger.info(f"DEM from Planetary Computer ({len(items)} tiles) -> {out}")
        return out
    except Exception as err:  # noqa: BLE001
        logger.warning(f"DEM from Planetary Computer failed: {err}. Trying AWS.")

    # 2) AWS public bucket, one 1x1 degree tile at a time (named by SW corner)
    try:
        dem = np.full((height, width), np.nan, dtype="float32")
        n_tiles = 0
        for lat in range(int(np.floor(lat_min)), int(np.floor(lat_max)) + 1):
            for lon in range(int(np.floor(lon_min)), int(np.floor(lon_max)) + 1):
                url = config.DEM_AWS_URL.format(ns="N" if lat >= 0 else "S", lat=abs(lat),
                                                ew="E" if lon >= 0 else "W", lon=abs(lon))
                try:
                    with rasterio.open("/vsicurl/" + url) as src:
                        reproject(source=rasterio.band(src, 1), destination=dem,
                                  dst_transform=transform, dst_crs=crs,
                                  resampling=Resampling.bilinear, dst_nodata=np.nan,
                                  init_dest_nodata=False)
                    n_tiles += 1
                except Exception as tile_err:  # noqa: BLE001
                    logger.warning(f"DEM tile {url} not read: {tile_err}")
        if n_tiles == 0 or not np.isfinite(dem).any():
            raise RuntimeError("no DEM tiles could be read")
        write_tif(out, dem, crs, transform, nodata=np.nan)
        logger.info(f"DEM from AWS ({n_tiles} tiles) -> {out}")
        return out
    except Exception as err:  # noqa: BLE001
        logger.warning(f"DEM from AWS failed: {err}. Elevation will be unavailable.")
        return None


def format_exception(err):
    """Short one-line description plus the full traceback (for the log)."""
    return f"{type(err).__name__}: {err}", traceback.format_exc()
