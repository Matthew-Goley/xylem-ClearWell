def _gadm_districts(paths, logger, state):
    import geopandas as gpd
    zpath = download_file(config.GADM_URL, paths.boundaries / "gadm41_IND_2.json.zip", logger)
    with zipfile.ZipFile(zpath) as z:
        name = [n for n in z.namelist() if n.endswith(".json")][0]
        z.extract(name, paths.boundaries)
    gdf = gpd.read_file(paths.boundaries / name)
    states = gdf["NAME_1"].unique().tolist()
    state_match = match_names([state], states)[0]["match"]
    if state_match is None:
        raise RuntimeError(f"State {state} not found in GADM")
    gdf = gdf[gdf["NAME_1"] == state_match].copy()
    gdf["district"] = gdf["NAME_2"]
    gdf["name_variants"] = gdf.get("VARNAME_2", "")
    return gdf[["district", "name_variants", "geometry"]]


def _geoboundaries_layer(paths, logger, level):
    import geopandas as gpd
    dest = paths.boundaries / f"geoBoundaries-IND-{level}_simplified.geojson"
    if not dest.exists():
        url = None
        try:
            session = http_session()
            resp = session.get(config.GEOBOUNDARIES_API.format(level=level), timeout=60)
            resp.raise_for_status()
            url = resp.json().get("simplifiedGeometryGeoJSON")
        except Exception as err:  # noqa: BLE001
            logger.info(f"geoBoundaries API not reachable ({err}); trying direct link")
        try:
            download_file(url or config.GEOBOUNDARIES_DIRECT.format(level=level), dest, logger)
        except Exception:
            if url is None:
                raise
            download_file(config.GEOBOUNDARIES_DIRECT.format(level=level), dest, logger)
    return gpd.read_file(dest)


def _geoboundaries_districts(paths, logger, state):
    adm1 = _geoboundaries_layer(paths, logger, "ADM1")
    adm2 = _geoboundaries_layer(paths, logger, "ADM2")
    state_match = match_names([state], adm1["shapeName"].tolist())[0]["match"]
    if state_match is None:
        raise RuntimeError(f"State {state} not found in geoBoundaries ADM1")
    state_geom = adm1[adm1["shapeName"] == state_match].geometry.union_all()
    # geoBoundaries ADM2 has no state column, so keep districts whose inside
    # point falls inside the state polygon.
    inside = adm2.geometry.representative_point().within(state_geom)
    gdf = adm2[inside].copy()
    gdf["district"] = gdf["shapeName"]
    gdf["name_variants"] = ""
    return gdf[["district", "name_variants", "geometry"]]


def get_districts(paths, logger, state=None):
    """All districts of the state as a GeoDataFrame in EPSG:4326.

    Returns (gdf, source). gdf is None if no boundary file could be obtained.
    The result is cached in data/boundaries/.
    """
    import geopandas as gpd
    state = state or config.STATE_NAME
    cache = paths.boundaries / f"{state.lower()}_districts.gpkg"
    source_file = paths.boundaries / f"{state.lower()}_districts_source.txt"
    if cache.exists():
        source = source_file.read_text().strip() if source_file.exists() else "cache"
        return gpd.read_file(cache), source
    for source, func in [("GADM 4.1", _gadm_districts), ("geoBoundaries", _geoboundaries_districts)]:
        try:
            gdf = func(paths, logger, state)
            gdf = gdf.to_crs("EPSG:4326")
            gdf["geometry"] = gdf.geometry.make_valid()
            gdf = gdf.reset_index(drop=True)
            gdf.to_file(cache, driver="GPKG")
            source_file.write_text(source)
            logger.info(f"District boundaries from {source}: {len(gdf)} districts in {state}")
            return gdf, source
        except Exception as err:  # noqa: BLE001
            logger.warning(f"District boundaries from {source} failed: {err}")
    loud_warning(logger, "No district boundary file could be downloaded. Falling back to the "
                         "bounding box in config.py (district names will be 'AOI').")
    return None, "none"


def select_districts(gdf, names):
    """Rows of gdf whose district names match names (using aliases and fuzzy matching)."""
    matches = match_names(names, gdf["district"].tolist())
    found = [m["match"] for m in matches if m["match"] is not None]
    return gdf[gdf["district"].isin(found)].copy(), matches


def districts_for_aoi(paths, aoi):
    """District polygons (UTM) for the AOI, or the AOI box if there are no boundaries."""
    import geopandas as gpd
    from shapely.geometry import box
    crs, transform, width, height = aoi_grid(aoi)
    gpkg = paths.outputs / "aoi_districts.gpkg"
    if gpkg.exists():
        return gpd.read_file(gpkg).to_crs(crs)
    xmin, ymin, xmax, ymax = grid_bounds(transform, width, height)
    return gpd.GeoDataFrame({"district": ["AOI"]}, geometry=[box(xmin, ymin, xmax, ymax)],
                            crs=crs)


