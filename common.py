def clean_name(name):
    """Lower case, no punctuation, single spaces. 'Kamrup (M)' -> 'kamrup m'."""
    text = str(name).lower().strip()
    text = re.sub(r"[^a-z0-9() ]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def match_names(queries, choices, min_score=None):
    """Match each query name to one of choices.

    Order: alias table in config, exact (case-insensitive), then rapidfuzz.
    Returns a list of dicts: query, match (or None), score, method.
    """
    from rapidfuzz import fuzz, process
    min_score = min_score if min_score is not None else config.FUZZY_MATCH_MIN_SCORE
    choices = list(choices)
    by_clean = {clean_name(c): c for c in choices}
    alias = {clean_name(k): v for k, v in config.DISTRICT_ALIASES.items()}
    out = []
    for q in queries:
        cq = clean_name(q)
        if cq in alias and clean_name(alias[cq]) in by_clean:
            out.append({"query": q, "match": by_clean[clean_name(alias[cq])], "score": 100.0,
                        "method": "alias"})
            continue
        if cq in by_clean:
            out.append({"query": q, "match": by_clean[cq], "score": 100.0, "method": "exact"})
            continue
        best = process.extractOne(cq, list(by_clean.keys()), scorer=fuzz.WRatio)
        if best and best[1] >= min_score:
            out.append({"query": q, "match": by_clean[best[0]], "score": float(best[1]),
                        "method": "fuzzy"})
        else:
            out.append({"query": q, "match": None, "score": float(best[1]) if best else 0.0,
                        "method": "unmatched"})
    return out


