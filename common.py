def get_logger(paths, stage):
    """Logger that prints to the console and appends to outputs/logs/<stage>.log."""
    paths.logs.mkdir(parents=True, exist_ok=True)
    logger = logging.getLogger(LOGGER_NAME)
    logger.setLevel(logging.INFO)
    # Remove handlers from a previous stage so each stage gets its own file.
    for handler in list(logger.handlers):
        logger.removeHandler(handler)
        handler.close()
    fmt = logging.Formatter("%(asctime)s %(levelname)-7s %(message)s", "%Y-%m-%d %H:%M:%S")
    console = logging.StreamHandler(sys.stdout)
    console.setFormatter(fmt)
    logger.addHandler(console)
    file_handler = logging.FileHandler(paths.logs / f"{stage}.log", encoding="utf-8")
    file_handler.setFormatter(fmt)
    logger.addHandler(file_handler)
    logger.propagate = False
    return logger


def loud_warning(logger, message):
    """A warning that is hard to miss in the log."""
    bar = "!" * 78
    logger.warning(bar)
    for line in str(message).splitlines():
        logger.warning("!! " + line)
    logger.warning(bar)


