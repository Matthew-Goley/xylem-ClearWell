def write_tif(path, array, crs, transform, nodata=None, dtype=None, band_names=None):
    """Write a 2D (H, W) or 3D (bands, H, W) array as a compressed GeoTIFF."""
    import rasterio
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    arr = array if array.ndim == 3 else array[None, ...]
    dtype = dtype or arr.dtype
    profile = {
        "driver": "GTiff", "height": arr.shape[1], "width": arr.shape[2],
        "count": arr.shape[0], "dtype": np.dtype(dtype).name, "crs": crs,
        "transform": transform, "compress": "lzw", "tiled": True,
        "blockxsize": 512, "blockysize": 512, "BIGTIFF": "IF_SAFER",
    }
    if nodata is not None:
        profile["nodata"] = nodata
    tmp = path.with_name(path.stem + ".tmp.tif")
    with rasterio.open(tmp, "w", **profile) as dst:
        dst.write(arr.astype(dtype, copy=False))
        if band_names:
            for i, name in enumerate(band_names, start=1):
                dst.set_band_description(i, name)
    os.replace(tmp, path)
    return path


def utm_epsg(lon, lat):
    """EPSG code of the UTM zone containing (lon, lat)."""
    zone = int((lon + 180) // 6) + 1
    return (32600 if lat >= 0 else 32700) + zone


def load_aoi(paths):
    """Read outputs/aoi.json written by export_s1.py."""
    if not paths.aoi.exists():
        raise FileNotFoundError(f"{paths.aoi} not found. Run stage export_s1 first.")
    with open(paths.aoi) as f:
        return json.load(f)


def aoi_grid(aoi):
    """Return (crs string, Affine transform, width, height) of the flood-map grid."""
    from affine import Affine
    g = aoi["grid"]
    return g["crs"], Affine(*g["transform"][:6]), int(g["width"]), int(g["height"])


def grid_bounds(transform, width, height):
    """(xmin, ymin, xmax, ymax) of a north-up grid."""
    xmin, ymax = transform.c, transform.f
    xmax = transform.c + width * transform.a
    ymin = transform.f + height * transform.e
    return xmin, ymin, xmax, ymax


def xy_to_rowcol(transform, x, y):
    """Map coordinates -> fractional (row, col) on a north-up grid."""
    col = (np.asarray(x, dtype=float) - transform.c) / transform.a
    row = (np.asarray(y, dtype=float) - transform.f) / transform.e
    return row, col


def scaled_transform(transform, factor):
    """Transform of the same grid with pixels `factor` times bigger (north-up)."""
    from affine import Affine
    return Affine(transform.a * factor, transform.b, transform.c,
                  transform.d, transform.e * factor, transform.f)


def pixel_area_km2(aoi):
    return (aoi["grid"]["pixel_size_m"] ** 2) / 1e6


def rasterize_districts(districts_utm, transform, width, height):
    """Raster of district index (1..n, 0 = outside) on the flood grid."""
    from rasterio import features
    shapes = [(geom, i + 1) for i, geom in enumerate(districts_utm.geometry)]
    return features.rasterize(shapes, out_shape=(height, width), transform=transform,
                              fill=0, dtype="uint8")


def block_reduce(arr, factor, func="mean"):
    """Downsample a 2D array by an integer factor (edges are trimmed)."""
    h = (arr.shape[0] // factor) * factor
    w = (arr.shape[1] // factor) * factor
    view = arr[:h, :w].reshape(h // factor, factor, w // factor, factor)
    if func == "max":
        return view.max(axis=(1, 3))
    if func == "sum":
        return view.sum(axis=(1, 3))
    if func == "nanmean":
        with np.errstate(invalid="ignore"):
            return np.nanmean(view, axis=(1, 3))
    return view.mean(axis=(1, 3))


