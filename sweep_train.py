"""
sweep_train.py - learning-rate sweep for Model 1, scored on the VALIDATION split only.

    python sweep_train.py                              # lr 1e-3, 3e-4, 1e-4 x 3 seeds
    python sweep_train.py --configs 1e-3:0.1           # add a config: decoder lr 1e-3, encoder 1e-4
    python sweep_train.py --report-only                # just rebuild the tables

A config is "lr" or "lr:encoder_multiplier". Each run uses train._fit (the same code as
the train stage) with a cosine schedule over config.MAX_EPOCHS and the early-stopping
patience from config.py. The best-validation checkpoint of every run goes to
outputs/sweep/. This script never reads the test or Bolivia split and never touches
outputs/unet.pt. Finished runs are cached in outputs/sweep/runs.json, so rerunning
only trains what is missing.

Writes results/model1_sweep.csv (one row per configuration) and results/model1_sweep.md.
"""

import argparse
import csv
import json

import numpy as np

import common
import config
import train

SEEDS = [42, 43, 44]
DEFAULT_CONFIGS = ["1e-3", "3e-4", "1e-4"]
WARMUP_EPOCHS = 5   # the first epochs always rise steeply, so noise is measured after them


def parse_config(text):
    lr, _, mult = text.partition(":")
    return float(lr), float(mult) if mult else 1.0


def config_name(lr, mult):
    return f"lr{lr:g}" + (f"_enc{mult:g}x" if mult != 1.0 else "")


def run_stats(rows):
    """Best val IoU and how noisy val IoU is from epoch to epoch for one run."""
    ious = np.array([r["val_iou"] for r in rows])
    best = float(ious.max())
    after = ious[WARMUP_EPOCHS:]
    jumps = np.abs(np.diff(after)) if len(after) > 1 else np.array([0.0])
    return {"best_val_iou": best, "best_epoch": int(ious.argmax()) + 1, "epochs_run": len(ious),
            "noise_mean_abs_change": float(jumps.mean()),
            "noise_max_change": float(jumps.max()),
            "collapse_epochs": int((after < 0.8 * best).sum()),
            "final_val_iou": float(ious[-1])}


def read_log(path):
    with open(path, newline="") as f:
        return [{k: float(v) for k, v in row.items()} for row in csv.DictReader(f)]


def aggregate(runs):
    by_config = {}
    for r in runs.values():
        by_config.setdefault(r["config"], []).append(r)
    table = []
    for name, rs in by_config.items():
        best = np.array([r["best_val_iou"] for r in rs])
        table.append({
            "config": name, "lr": rs[0]["lr"], "encoder_lr_mult": rs[0]["encoder_lr_mult"],
            "n_seeds": len(rs),
            "val_iou_mean": best.mean(),
            "val_iou_std": best.std(ddof=1) if len(rs) > 1 else float("nan"),
            "val_iou_min": best.min(), "val_iou_max": best.max(),
            "best_epoch_mean": np.mean([r["best_epoch"] for r in rs]),
            "epochs_run_mean": np.mean([r["epochs_run"] for r in rs]),
            "noise_mean_abs_change": np.mean([r["noise_mean_abs_change"] for r in rs]),
            "noise_max_change": np.max([r["noise_max_change"] for r in rs]),
            "collapse_epochs_mean": np.mean([r["collapse_epochs"] for r in rs]),
            "final_val_iou_mean": np.mean([r["final_val_iou"] for r in rs]),
        })
    return sorted(table, key=lambda t: -t["val_iou_mean"])


def write_reports(paths, table):
    fields = list(table[0].keys())
    with open(paths.results / "model1_sweep.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in table:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in row.items()})
    lines = [
        "# Model 1 learning-rate sweep (validation split only)",
        "",
        f"Generated by sweep_train.py. {len(table)} configurations x {table[0]['n_seeds']} seeds, "
        f"cosine schedule over {config.MAX_EPOCHS} epochs, early-stopping patience "
        f"{config.EARLY_STOP_PATIENCE}, AdamW weight decay {config.WEIGHT_DECAY}. "
        "Nothing here uses the test or Bolivia tiles.",
        "",
        "- **val IoU**: best validation water IoU of a run; mean and standard deviation across seeds.",
        f"- **noise**: mean absolute change of val IoU between consecutive epochs, after epoch "
        f"{WARMUP_EPOCHS} (lower = steadier training).",
        "- **collapses**: epochs (after the warm-up) whose val IoU fell below 80% of that run's best.",
        "",
        "| Config | val IoU mean | std | min | max | best epoch | noise | worst jump | collapses | final val IoU |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for t in table:
        lines.append(f"| {t['config']} | {t['val_iou_mean']:.3f} | {t['val_iou_std']:.3f} | "
                     f"{t['val_iou_min']:.3f} | {t['val_iou_max']:.3f} | {t['best_epoch_mean']:.0f} | "
                     f"{t['noise_mean_abs_change']:.3f} | {t['noise_max_change']:.3f} | "
                     f"{t['collapse_epochs_mean']:.1f} | {t['final_val_iou_mean']:.3f} |")
    (paths.results / "model1_sweep.md").write_text("\n".join(lines) + "\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--configs", nargs="*", default=None,
                        help="configs as lr or lr:encoder_multiplier (default: the three lrs)")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args(argv)

    paths = config.get_paths(False)
    sweep_dir = paths.outputs / "sweep"
    sweep_dir.mkdir(parents=True, exist_ok=True)
    cache = sweep_dir / "runs.json"
    runs = json.loads(cache.read_text()) if cache.exists() else {}
    logger = common.get_logger(paths, "sweep")

    if not args.report_only:
        device = train.get_device()
        for text in (args.configs or DEFAULT_CONFIGS):
            lr, mult = parse_config(text)
            name = config_name(lr, mult)
            for seed in SEEDS:
                key = f"{name}_seed{seed}"
                if key in runs:
                    logger.info(f"{key}: already done (val IoU {runs[key]['best_val_iou']:.4f})")
                    continue
                log_path = sweep_dir / f"{key}_log.csv"
                logger.info(f"===== {key} =====")
                train._fit(paths, logger, False, config.BATCH_SIZE, device, lr=lr,
                           encoder_lr_mult=mult, seed=seed, ckpt_path=sweep_dir / f"{key}.pt",
                           log_path=log_path, save_curves=False)
                runs[key] = {"config": name, "lr": lr, "encoder_lr_mult": mult, "seed": seed,
                             **run_stats(read_log(log_path))}
                cache.write_text(json.dumps(runs, indent=2))
                logger.info(f"{key}: best val IoU {runs[key]['best_val_iou']:.4f} at epoch "
                            f"{runs[key]['best_epoch']}, noise {runs[key]['noise_mean_abs_change']:.3f}")

    if runs:
        table = aggregate(runs)
        write_reports(paths, table)
        print((paths.results / "model1_sweep.md").read_text())


if __name__ == "__main__":
    main()
